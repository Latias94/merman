#!/usr/bin/env python3
"""Tests for the Flutter release archive owner boundary."""

from __future__ import annotations

import hashlib
import io
import json
from pathlib import Path
import sys
import tarfile
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))

from flutter_native_assets import MANIFEST_PATH, TARGET_LIBRARIES, stage
from flutter_release_archive import (
    ARCHIVE_NAME,
    DEFAULT_LIMITS,
    PACKAGE_NAME,
    RECEIPT_NAME,
    SCHEMA_VERSION,
    ArchiveLimits,
    FlutterReleaseArchiveError,
    create_archive,
    verify_and_extract,
)


SOURCE_SHA = "1" * 40
SOURCE_TREE = "2" * 40
NATIVE_SOURCE_SHA = "3" * 40
NATIVE_SOURCE_TREE = "4" * 40
VERSION = "0.8.0-alpha.5"


def raw_member(
    name: str,
    data: bytes = b"",
    member_type: bytes = tarfile.REGTYPE,
    linkname: str = "",
) -> tuple[tarfile.TarInfo, bytes]:
    info = tarfile.TarInfo(name)
    info.type = member_type
    info.mode = 0o644
    info.size = len(data) if info.isreg() else 0
    info.linkname = linkname
    return info, data


class FlutterReleaseArchiveTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary_directory = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary_directory.name)

    def tearDown(self) -> None:
        self.temporary_directory.cleanup()

    def test_pack_and_extract_bind_identity_and_ignore_transient_files(self) -> None:
        root = self.case("roundtrip")
        package_root = root / "package"
        self.write_package(package_root)
        (package_root / ".dart_tool").mkdir()
        (package_root / ".dart_tool" / "package_config.json").write_text(
            "/private/runner/path\n", encoding="utf-8"
        )
        (package_root / "tool" / "__pycache__").mkdir(parents=True)
        (package_root / "tool" / "__pycache__" / "owner.pyc").write_bytes(b"cache")
        (package_root / ".gitignore").write_text(".dart_tool/\n", encoding="utf-8")
        (package_root / ".pubignore").write_text(
            "/build-native.py\n/ffigen.yaml\n",
            encoding="utf-8",
        )
        (package_root / "build-native.py").write_text(
            "raise SystemExit(0)\n",
            encoding="utf-8",
        )
        (package_root / "ffigen.yaml").write_text(
            "output: generated.dart\n",
            encoding="utf-8",
        )
        (package_root / "pubspec.lock").write_text(
            "# Generated by pub\npackages: {}\n",
            encoding="utf-8",
        )

        archive = root / ARCHIVE_NAME
        receipt = root / RECEIPT_NAME
        created = create_archive(
            package_root,
            archive,
            receipt,
            source_sha=SOURCE_SHA,
            source_tree=SOURCE_TREE,
            version=VERSION,
        )
        destination = root / "publish"
        verified = self.verify(archive, receipt, destination)

        self.assertEqual(created, verified)
        self.assertEqual(
            (destination / "lib" / "merman.dart").read_text(encoding="utf-8"),
            "library merman;\n",
        )
        self.assertFalse((destination / ".dart_tool").exists())
        self.assertFalse((destination / "tool" / "__pycache__").exists())
        for relative in (
            ".gitignore",
            ".pubignore",
            "build-native.py",
            "ffigen.yaml",
            "pubspec.lock",
        ):
            with self.subTest(relative=relative):
                self.assertFalse((destination / relative).exists())

    def test_receipt_binds_source_tree_version_and_archive_digest(self) -> None:
        root = self.case("identity")
        archive, receipt = self.create_valid_artifact(root)
        mismatches = (
            ("source_sha", "3" * 40, SOURCE_TREE, VERSION),
            ("source_tree", SOURCE_SHA, "4" * 40, VERSION),
            ("version", SOURCE_SHA, SOURCE_TREE, "0.8.0-alpha.6"),
        )
        for label, source_sha, source_tree, version in mismatches:
            with self.subTest(label=label), self.assertRaisesRegex(
                FlutterReleaseArchiveError, "release identity"
            ):
                verify_and_extract(
                    archive,
                    receipt,
                    root / f"publish-{label}",
                    expected_source_sha=source_sha,
                    expected_source_tree=source_tree,
                    expected_version=version,
                )

        with archive.open("ab") as stream:
            stream.write(b"tampered")
        with self.assertRaisesRegex(FlutterReleaseArchiveError, "digest"):
            self.verify(archive, receipt, root / "publish-digest")

    def test_thin_archive_composes_distinct_sources_and_preserves_original_manifest(self):
        root = self.case("thin")
        package = root / "package"
        self.write_package(package)
        manifest_path = self.write_native_manifest(root)
        manifest_bytes = b"\r\n" + manifest_path.read_bytes().replace(b"\n", b"\r\n") + b"\t\r\n"
        manifest_path.write_bytes(manifest_bytes)
        (package / "tool").mkdir()
        (package / "tool/owner.dart").write_text("repository only")
        (package / "hook").mkdir()
        (package / MANIFEST_PATH).write_text("{}\n", encoding="utf-8")
        archive, receipt = root / ARCHIVE_NAME, root / RECEIPT_NAME
        created = create_archive(
            package, archive, receipt, source_sha=SOURCE_SHA,
            source_tree=SOURCE_TREE, version=VERSION,
            native_manifest=manifest_path,
        )
        self.assertEqual(created, {
            "schema_version": SCHEMA_VERSION,
            "package": PACKAGE_NAME,
            "version": VERSION,
            "source_sha": SOURCE_SHA,
            "source_tree": SOURCE_TREE,
            "archive_sha256": hashlib.sha256(archive.read_bytes()).hexdigest(),
        })
        with tarfile.open(archive, "r:gz") as packed:
            with packed.extractfile(MANIFEST_PATH) as manifest:
                self.assertEqual(manifest.read(), manifest_bytes)
        destination = root / "publish"
        verified = self.verify(archive, receipt, destination, require_thin=True)
        self.assertEqual(created, verified)
        self.assertFalse((destination / "native").exists())
        self.assertFalse((destination / "tool").exists())
        self.assertEqual((destination / MANIFEST_PATH).read_bytes(), manifest_bytes)
        self.assertEqual(manifest_path.read_bytes(), manifest_bytes)
        manifest = json.loads(manifest_bytes)
        self.assertEqual(manifest["source_sha"], NATIVE_SOURCE_SHA)
        self.assertEqual(manifest["source_tree"], NATIVE_SOURCE_TREE)
        self.assertTrue(all(
            entry["url"].startswith(f"https://example.org/flutter-v{VERSION}/")
            for entry in manifest["targets"].values()
        ))

    def test_original_schema1_alpha_archive_and_receipt_remain_extractable(self) -> None:
        root = self.case("original-alpha")
        manifest_path = self.write_native_manifest(
            root, source_sha=SOURCE_SHA, source_tree=SOURCE_TREE,
        )
        manifest_bytes = manifest_path.read_bytes()
        archive, receipt = self.write_raw_artifact(
            root, [raw_member(MANIFEST_PATH, manifest_bytes)],
        )
        archive_bytes, receipt_bytes = archive.read_bytes(), receipt.read_bytes()
        destination = root / "publish"

        verified = self.verify(archive, receipt, destination, require_thin=True)

        self.assertEqual(verified, json.loads(receipt_bytes))
        self.assertEqual((destination / MANIFEST_PATH).read_bytes(), manifest_bytes)
        self.assertEqual(archive.read_bytes(), archive_bytes)
        self.assertEqual(receipt.read_bytes(), receipt_bytes)

    def test_pack_and_extract_reject_wrong_native_version(self) -> None:
        root = self.case("wrong-native-version")
        manifest_path = self.write_native_manifest(root, version="0.8.0-alpha.6")
        self.assert_native_manifest_rejected(
            root, manifest_path.read_bytes(), "version identity differs",
        )

    def test_pack_and_extract_reject_malformed_native_identity_and_targets(self) -> None:
        root = self.case("malformed-native")
        manifest = json.loads(self.write_native_manifest(root).read_bytes())
        for name, field, value, pattern in (
            ("schema", "schema_version", 2, "schema"),
            ("package", "package", "other", "package identity"),
            ("source-sha", "source_sha", "not-a-sha", "source_sha identity"),
            ("source-tree", "source_tree", None, "source_tree identity"),
            ("missing-targets", "targets", {}, "supported targets"),
        ):
            with self.subTest(name=name):
                self.assert_native_manifest_rejected(
                    self.case(name), json.dumps({**manifest, field: value}).encode(), pattern,
                )

        target = "macos/arm64"
        entry = manifest["targets"][target]
        for name, field, value, pattern in (
            ("asset-path", "asset", "../escape.gz", "asset name"),
            ("library-path", "library", "../escape.dylib", "library name"),
            ("asset-hash", "sha256", "not-a-digest", "native sha256"),
            ("library-hash", "library_sha256", "0" * 63, "native library_sha256"),
            ("asset-size", "size", 0, "native size"),
            ("library-size", "library_size", -1, "native library_size"),
            ("asset-url", "url", "https://example.org/wrong.gz", "asset URL"),
        ):
            with self.subTest(name=name):
                changed = {
                    **manifest,
                    "targets": {**manifest["targets"], target: {**entry, field: value}},
                }
                self.assert_native_manifest_rejected(
                    self.case(name), json.dumps(changed).encode(), pattern,
                )

        for name, data in (("invalid-json", b"{"), ("not-an-object", b"[]")):
            with self.subTest(name=name):
                self.assert_native_manifest_rejected(
                    self.case(name), data, "cannot read.*manifest|manifest schema",
                )

    def test_thin_archive_digest_rejects_changed_native_manifest(self) -> None:
        root = self.case("manifest-tamper")
        package = root / "package"
        self.write_package(package)
        manifest_path = self.write_native_manifest(root)
        archive, receipt = root / ARCHIVE_NAME, root / RECEIPT_NAME
        create_archive(
            package, archive, receipt, source_sha=SOURCE_SHA,
            source_tree=SOURCE_TREE, version=VERSION, native_manifest=manifest_path,
        )
        manifest = json.loads(manifest_path.read_bytes())
        manifest["targets"]["macos/arm64"]["library_sha256"] = "a" * 64
        tampered = root / "tampered.tar.gz"
        with tarfile.open(archive, "r:gz") as original, tarfile.open(tampered, "w:gz") as changed:
            for member in original:
                with original.extractfile(member) as source:
                    data = source.read()
                if member.name == MANIFEST_PATH:
                    data = json.dumps(manifest).encode()
                    member.size = len(data)
                changed.addfile(member, io.BytesIO(data))
        tampered.replace(archive)
        destination = root / "publish"

        with self.assertRaisesRegex(FlutterReleaseArchiveError, "archive digest"):
            self.verify(archive, receipt, destination, require_thin=True)
        self.assertFalse(destination.exists())

    def test_required_thin_extraction_rejects_legacy_package_before_writing(self):
        root = self.case("require-thin")
        archive, receipt = self.create_valid_artifact(root)
        destination = root / "publish"
        with self.assertRaisesRegex(FlutterReleaseArchiveError, "thin archive"):
            verify_and_extract(
                archive, receipt, destination, expected_source_sha=SOURCE_SHA,
                expected_source_tree=SOURCE_TREE, expected_version=VERSION, require_thin=True,
            )
        self.assertFalse(destination.exists())

    def test_receipt_read_is_bounded_and_duplicate_keys_are_rejected(self) -> None:
        root = self.case("large-receipt")
        archive, receipt = self.create_valid_artifact(root)
        receipt.write_bytes(b"{" + b" " * (32 * 1024) + b"}")
        with self.assertRaisesRegex(FlutterReleaseArchiveError, "receipt exceeds"):
            self.verify(archive, receipt, root / "publish")

        root = self.case("duplicate-receipt")
        archive, receipt = self.create_valid_artifact(root)
        receipt.write_text('{"schema_version": 1, "schema_version": 1}\n', encoding="utf-8")
        with self.assertRaisesRegex(FlutterReleaseArchiveError, "duplicate key"):
            self.verify(archive, receipt, root / "publish")

    def test_rejects_absolute_and_traversal_paths(self) -> None:
        for index, path in enumerate(("/tmp/escape", "../escape", "lib/../../escape", "lib\\escape")):
            with self.subTest(path=path):
                self.assert_raw_rejected(
                    f"unsafe-path-{index}",
                    [raw_member(path, b"escape")],
                    "absolute|traversal|backslash",
                )

    def test_rejects_links_devices_and_other_non_regular_members(self) -> None:
        attacks = (
            ("link", tarfile.SYMTYPE, "pubspec.yaml"),
            ("hard-link", tarfile.LNKTYPE, "pubspec.yaml"),
            ("device", tarfile.CHRTYPE, ""),
            ("fifo", tarfile.FIFOTYPE, ""),
        )
        for name, member_type, linkname in attacks:
            with self.subTest(member_type=member_type):
                self.assert_raw_rejected(
                    f"member-{name}",
                    [raw_member(name, member_type=member_type, linkname=linkname)],
                    "not a regular file",
                )

    def test_rejects_duplicate_portable_collision_and_file_ancestor(self) -> None:
        attacks = (
            (
                "duplicate",
                [raw_member("lib/repeated", b"one"), raw_member("lib/repeated", b"two")],
                "duplicate",
            ),
            (
                "case-collision",
                [raw_member("lib/Foo.dart", b"one"), raw_member("lib/foo.dart", b"two")],
                "portable path collision",
            ),
            (
                "unicode-collision",
                [
                    raw_member("lib/caf\N{LATIN SMALL LETTER E WITH ACUTE}.dart", b"one"),
                    raw_member("lib/cafe\N{COMBINING ACUTE ACCENT}.dart", b"two"),
                ],
                "portable path collision",
            ),
            (
                "ancestor",
                [raw_member("lib", b"file"), raw_member("lib/child.dart", b"child")],
                "ancestor",
            ),
        )
        for name, additions, pattern in attacks:
            with self.subTest(name=name):
                self.assert_raw_rejected(name, additions, pattern)

    def test_rejects_member_and_member_count_budget_overruns(self) -> None:
        self.assert_raw_rejected(
            "member-size",
            [raw_member("large.bin", b"x" * 128)],
            "size budget",
            limits=ArchiveLimits(max_member_bytes=64),
        )
        self.assert_raw_rejected(
            "member-count",
            [raw_member("extra.txt", b"x")],
            "member-count budget",
            limits=ArchiveLimits(max_members=3),
        )

    def test_rejects_oversized_pax_metadata_before_member_admission(self) -> None:
        self.assert_raw_rejected(
            "pax-metadata",
            [],
            "decompressed tar",
            limits=ArchiveLimits(
                max_total_bytes=4096,
                max_metadata_bytes=20 * 1024,
            ),
            pax_comment="x" * (64 * 1024),
        )

    def test_refuses_to_write_into_an_existing_destination(self) -> None:
        root = self.case("existing-destination")
        archive, receipt = self.create_valid_artifact(root)
        destination = root / "publish"
        destination.mkdir()
        sentinel = destination / "sentinel"
        sentinel.write_text("keep", encoding="utf-8")

        with self.assertRaisesRegex(FlutterReleaseArchiveError, "must not already exist"):
            self.verify(archive, receipt, destination)
        self.assertEqual(sentinel.read_text(encoding="utf-8"), "keep")

    def test_rejects_archive_pubspec_version_drift(self) -> None:
        self.assert_raw_rejected(
            "pubspec-drift",
            [],
            "version does not match",
            pubspec_version="0.8.0-alpha.6",
        )

    def case(self, name: str) -> Path:
        root = self.root / name
        root.mkdir()
        return root

    @staticmethod
    def write_package(package_root: Path) -> None:
        (package_root / "lib").mkdir(parents=True)
        (package_root / "pubspec.yaml").write_text(
            f"name: {PACKAGE_NAME}\nversion: {VERSION}\n", encoding="utf-8"
        )
        (package_root / "LICENSE").write_text("license\n", encoding="utf-8")
        (package_root / "THIRD_PARTY_NOTICES.md").write_text("notices\n", encoding="utf-8")
        (package_root / "lib" / "merman.dart").write_text(
            "library merman;\n", encoding="utf-8"
        )

    def create_valid_artifact(self, root: Path) -> tuple[Path, Path]:
        package_root = root / "package"
        self.write_package(package_root)
        archive = root / ARCHIVE_NAME
        receipt = root / RECEIPT_NAME
        create_archive(
            package_root,
            archive,
            receipt,
            source_sha=SOURCE_SHA,
            source_tree=SOURCE_TREE,
            version=VERSION,
        )
        return archive, receipt

    @staticmethod
    def write_native_manifest(
        root: Path,
        *,
        version: str = VERSION,
        source_sha: str = NATIVE_SOURCE_SHA,
        source_tree: str = NATIVE_SOURCE_TREE,
    ) -> Path:
        native_root = root / "package/native"
        for target, library in TARGET_LIBRARIES.items():
            path = native_root / target / library
            path.parent.mkdir(parents=True)
            path.write_bytes(f"frozen native fixture: {target}".encode())
        stage(
            native_root, root / "assets", version=version,
            source_sha=source_sha, source_tree=source_tree,
            base_url=f"https://example.org/flutter-v{version}/",
        )
        return root / "assets/native-assets.json"

    def assert_native_manifest_rejected(self, root: Path, data: bytes, pattern: str) -> None:
        package = root / "package"
        self.write_package(package)
        manifest_path = root / "invalid-native-assets.json"
        manifest_path.write_bytes(data)
        archive, receipt = root / ARCHIVE_NAME, root / RECEIPT_NAME
        with self.assertRaisesRegex(FlutterReleaseArchiveError, pattern):
            create_archive(
                package, archive, receipt, source_sha=SOURCE_SHA,
                source_tree=SOURCE_TREE, version=VERSION, native_manifest=manifest_path,
            )
        self.assertFalse(archive.exists())
        self.assertFalse(receipt.exists())
        archive, receipt = self.write_raw_artifact(root, [raw_member(MANIFEST_PATH, data)])
        with self.assertRaisesRegex(FlutterReleaseArchiveError, pattern):
            self.verify(archive, receipt, root / "publish", require_thin=True)

    @staticmethod
    def write_raw_artifact(
        root: Path,
        additions: list[tuple[tarfile.TarInfo, bytes]],
        *,
        pubspec_version: str = VERSION,
        pax_comment: str | None = None,
    ) -> tuple[Path, Path]:
        archive_path = root / ARCHIVE_NAME
        receipt_path = root / RECEIPT_NAME
        members = [
            raw_member(
                "pubspec.yaml",
                f"name: {PACKAGE_NAME}\nversion: {pubspec_version}\n".encode(),
            ),
            raw_member("LICENSE", b"license\n"),
            raw_member("THIRD_PARTY_NOTICES.md", b"notices\n"),
            *additions,
        ]
        with tarfile.open(archive_path, "w:gz", format=tarfile.PAX_FORMAT) as archive:
            for info, data in members:
                if pax_comment is not None and info.name == "pubspec.yaml":
                    info.pax_headers["comment"] = pax_comment
                archive.addfile(info, io.BytesIO(data) if info.size else None)

        archive_bytes = archive_path.read_bytes()
        receipt = {
            "archive_sha256": hashlib.sha256(archive_bytes).hexdigest(),
            "package": PACKAGE_NAME,
            "schema_version": SCHEMA_VERSION,
            "source_sha": SOURCE_SHA,
            "source_tree": SOURCE_TREE,
            "version": VERSION,
        }
        receipt_path.write_text(json.dumps(receipt), encoding="utf-8")
        return archive_path, receipt_path

    def assert_raw_rejected(
        self,
        name: str,
        additions: list[tuple[tarfile.TarInfo, bytes]],
        pattern: str,
        *,
        limits: ArchiveLimits = DEFAULT_LIMITS,
        **archive_options: object,
    ) -> None:
        root = self.case(name)
        archive, receipt = self.write_raw_artifact(root, additions, **archive_options)
        with self.assertRaisesRegex(FlutterReleaseArchiveError, pattern):
            self.verify(archive, receipt, root / "publish", limits=limits)

    @staticmethod
    def verify(
        archive: Path,
        receipt: Path,
        destination: Path,
        *,
        require_thin: bool = False,
        limits: ArchiveLimits = DEFAULT_LIMITS,
    ) -> dict[str, object]:
        return verify_and_extract(
            archive,
            receipt,
            destination,
            expected_source_sha=SOURCE_SHA,
            expected_source_tree=SOURCE_TREE,
            expected_version=VERSION,
            require_thin=require_thin,
            limits=limits,
        )


if __name__ == "__main__":
    unittest.main()
