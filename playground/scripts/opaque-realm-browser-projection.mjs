import path from "node:path";

import {
  engineForId,
  publicEnginePath,
} from "./opaque-realm-artifact-plan.mjs";

const HEADER = `// This file is generated by scripts/build-opaque-realm.mjs.\n// Do not edit it directly.\n`;

export function renderOpaqueRealmBrowserProjections(plan) {
  const projections = new Map();
  projections.set(
    plan.browserMetadataModule,
    renderMetadataProjection(plan),
  );
  for (const realm of plan.realms) {
    if (!realm.bootstrap) continue;
    projections.set(
      realm.bootstrap.browserProjection.module,
      renderOpaqueRealmProjection(plan, realm),
    );
  }
  for (const engine of plan.engines) {
    if (!engine.browserProjection) continue;
    projections.set(
      engine.browserProjection.module,
      renderEngineProjection(plan, engine),
    );
  }
  return projections;
}

function renderMetadataProjection(plan) {
  const ids = plan.engines.map((engine) => JSON.stringify(engine.id)).join(", ");
  const exportEntries = plan.engines
    .map(
      (engine) =>
        `  ${JSON.stringify(engine.id)}: Object.freeze(${JSON.stringify(engine.exports)}),`,
    )
    .join("\n");
  const policyEntries = plan.engines
    .map(
      (engine) =>
        `  ${JSON.stringify(engine.id)}: ${JSON.stringify(engine.resourcePolicy)},`,
    )
    .join("\n");
  return `${HEADER}
export const REALM_ENGINE_ARTIFACT_IDS = Object.freeze([${ids}] as const);

export type RealmEngineArtifactId =
  (typeof REALM_ENGINE_ARTIFACT_IDS)[number];

export const REALM_ENGINE_MODULE_EXPORTS = Object.freeze({
${exportEntries}
} as const);

export const REALM_ENGINE_RESOURCE_POLICIES = Object.freeze({
${policyEntries}
} as const);

export function isRealmEngineArtifactId(
  value: unknown,
): value is RealmEngineArtifactId {
  return (
    typeof value === "string" &&
    Object.prototype.hasOwnProperty.call(REALM_ENGINE_RESOURCE_POLICIES, value)
  );
}
`;
}

function renderOpaqueRealmProjection(plan, realm) {
  const engine = engineForId(plan, realm.engine);
  const moduleFile = realm.bootstrap.browserProjection.module;
  const runtimeType = relativeImport(
    moduleFile,
    "src/runtime/realm/opaque-realm-projection.ts",
  );
  const bootstrapSource = relativeImport(
    moduleFile,
    `${plan.roots.generated}/${realm.bootstrap.outputBase}.js`,
  );
  const bootstrapManifest = relativeImport(
    moduleFile,
    `${plan.roots.generated}/${realm.bootstrap.outputBase}.json`,
  );
  const engineManifest = relativeImport(
    moduleFile,
    `${plan.roots.generated}/${engine.outputBase}.json`,
  );
  return `${HEADER}
import bootstrapSource from ${JSON.stringify(`${bootstrapSource}?raw`)};
import bootstrapManifest from ${JSON.stringify(bootstrapManifest)};
import engineManifest from ${JSON.stringify(engineManifest)};

import type { OpaqueRealmArtifactProjection } from ${JSON.stringify(runtimeType)};

export const ${realm.bootstrap.browserProjection.exportName}: OpaqueRealmArtifactProjection =
  Object.freeze({
    bootstrap: Object.freeze({
      manifest: bootstrapManifest,
      source: bootstrapSource,
    }),
    engine: Object.freeze({
      manifest: engineManifest,
      publicPath: ${JSON.stringify(publicEnginePath(plan, engine))},
      resourcePolicy: ${JSON.stringify(engine.resourcePolicy)},
    }),
    realm: Object.freeze({
      key: ${JSON.stringify(realm.key)},
      kind: ${JSON.stringify(realm.kind)},
    }),
  });
`;
}

function renderEngineProjection(plan, engine) {
  const moduleFile = engine.browserProjection.module;
  const runtimeType = relativeImport(
    moduleFile,
    "src/runtime/realm/opaque-realm-projection.ts",
  );
  const engineManifest = relativeImport(
    moduleFile,
    `${plan.roots.generated}/${engine.outputBase}.json`,
  );
  return `${HEADER}
import engineManifest from ${JSON.stringify(engineManifest)};

import type { RealmEngineArtifactProjection } from ${JSON.stringify(runtimeType)};

export const ${engine.browserProjection.exportName}: RealmEngineArtifactProjection =
  Object.freeze({
    manifest: engineManifest,
    publicPath: ${JSON.stringify(publicEnginePath(plan, engine))},
    resourcePolicy: ${JSON.stringify(engine.resourcePolicy)},
  });
`;
}

function relativeImport(fromModule, toModule) {
  const relative = path.posix.relative(path.posix.dirname(fromModule), toModule);
  return relative.startsWith(".") ? relative : `./${relative}`;
}
