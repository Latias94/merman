pub(crate) fn is_mermaid_unicode_text(ch: char) -> bool {
    let code = ch as u32;
    MERMAID_UNICODE_TEXT_RANGES
        .binary_search_by(|&(start, end)| {
            if code < start {
                std::cmp::Ordering::Greater
            } else if code > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
